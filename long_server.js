const express = require('express');
const cors = require('cors');

const app = express();
const port = 3001;

// Enable CORS and JSON parsing
app.use(cors());
app.use(express.json());

// --- CONFIGURATION ---
// Use gemini-2.5-flash as requested by user
const GEMINI_MODEL_NAME = "gemini-2.5-flash";
// TODO: Replace with your actual Gemini API Key
const API_KEY = "AIzaSyB5wZ_yHDdLgU-_B0lBBCNxCOfRyTCgeNs";

// --- API ENDPOINT ---
app.post('/long-qa', async (req, res) => {
    try {
        const { text } = req.body;

        // 1. Validation
        if (!text) {
            return res.status(400).json({ error: "No text provided" });
        }

        // 2. Prepare the prompt
        // Requirement: ONE long question and answer (~300 words), simple English, exam-oriented.
        const prompt = `
            Based on the following text, generate EXACTLY ONE long-form question and a detailed answer.
            
            Format:
            Q: [Question]
            A: [Answer]

            Requirements:
            - The answer must be approximately 280-320 words long.
            - Use simple, clear English suitable for exams.
            - If the input text is short, logically expand on the topic to meet the length requirement.
            - Do NOT use markdown symbols like ** or ##.

            Input Text:
            "${text}"
        `;

        // 3. Call Gemini API using native fetch
        // USING v1 API endpoint as requested
        const apiUrl = `https://generativelanguage.googleapis.com/v1/models/${GEMINI_MODEL_NAME}:generateContent?key=${API_KEY}`;

        const response = await fetch(apiUrl, {
            method: 'POST',
            headers: {
                'Content-Type': 'application/json'
            },
            body: JSON.stringify({
                contents: [{
                    parts: [{ text: prompt }]
                }]
            })
        });

        // 4. Handle API Response
        if (!response.ok) {
            const errorData = await response.json();
            throw new Error(`Gemini API Error: ${errorData.error?.message || response.statusText}`);
        }

        const data = await response.json();
        const generatedText = data.candidates?.[0]?.content?.parts?.[0]?.text;

        if (!generatedText) {
            throw new Error("No content generated by the model.");
        }

        // 5. Send back the result
        res.json({ result: generatedText });

    } catch (error) {
        console.error("Server Error:", error);
        res.status(500).json({ error: error.message });
    }
});

// Start the server
app.listen(port, () => {
    console.log(`Server running at http://localhost:${port}`);
});
